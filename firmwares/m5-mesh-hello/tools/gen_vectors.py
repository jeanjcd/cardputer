#!/usr/bin/env python3
"""Deterministic reference-vector generator. Writes test/vectors.h."""
import hashlib, os, struct
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESCCM
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from cryptography.hazmat.primitives import serialization as ser

DEFAULT_KEY = bytes.fromhex("d4f1bb3a20290759f0bcffabcf4e6901")
ID, FROM, EXTRA = 0x12345678, 0xA1B2C3D4, 0xCAFEBABE

# CTR
ctr_pt = b"Hello Meshtastic! CTR test vector 012345"  # 40 bytes
assert len(ctr_pt) == 40
ctr_nonce = struct.pack("<QI", ID, FROM) + b"\x00" * 4
enc = Cipher(algorithms.AES(DEFAULT_KEY), modes.CTR(ctr_nonce)).encryptor()
ctr_ct = enc.update(ctr_pt) + enc.finalize()

# X25519
priv_a = bytes(range(1, 33))
priv_b = bytes(range(101, 133))
ka = X25519PrivateKey.from_private_bytes(priv_a)
kb = X25519PrivateKey.from_private_bytes(priv_b)
raw = lambda k: k.public_key().public_bytes(ser.Encoding.Raw, ser.PublicFormat.Raw)
pub_a, pub_b = raw(ka), raw(kb)
shared = ka.exchange(kb.public_key())
assert shared == kb.exchange(ka.public_key())
aes256 = hashlib.sha256(shared).digest()

# CCM
ccm_pt = b"PKI direct message test vector"
assert len(ccm_pt) == 30
ccm_nonce = struct.pack("<III", ID, EXTRA, FROM) + b"\x00"
out = AESCCM(aes256, tag_length=8).encrypt(ccm_nonce, ccm_pt, None)
ccm_ct, ccm_tag = out[:-8], out[-8:]
ccm_wire = ccm_ct + ccm_tag + struct.pack("<I", EXTRA)

def arr(name, data):
    body = ",".join("0x%02x" % b for b in data)
    return "static const uint8_t %s[%d] = {%s};\nstatic const size_t %s_LEN = %d;\n" % (
        name, len(data), body, name, len(data))

hdr = """// GENERATED by tools/gen_vectors.py - do not edit.
// Reference vectors produced with Python 'cryptography'.
// CTR_*: AES-128-CTR, key = default channel key, counter block =
//   packetId u64 LE | fromNode u32 LE | 4 zero bytes (id=0x12345678, from=0xA1B2C3D4).
// X25519_*: raw private keys A/B, their public keys, and the shared secret.
// AES256_KEY: SHA-256(shared secret), used as the PKI AES-256 key.
// CCM_*: AES-256-CCM, tag 8, no AAD, nonce(13) = id_low32 LE | extraNonce LE | from LE | 0x00,
//   extraNonce=0xCAFEBABE. CCM_CIPHER/CCM_TAG are separate; CCM_WIRE = cipher | tag | extraNonce(4 LE).
#pragma once
#include <stddef.h>
#include <stdint.h>

"""
parts = [("CTR_PLAIN", ctr_pt), ("CTR_CIPHER", ctr_ct), ("X25519_PRIV_A", priv_a),
         ("X25519_PRIV_B", priv_b), ("X25519_PUB_A", pub_a), ("X25519_PUB_B", pub_b),
         ("X25519_SHARED", shared), ("AES256_KEY", aes256), ("CCM_PLAIN", ccm_pt),
         ("CCM_CIPHER", ccm_ct), ("CCM_TAG", ccm_tag), ("CCM_WIRE", ccm_wire)]
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "test", "vectors.h")
with open(path, "w", newline="\n") as f:
    f.write(hdr + "\n".join(arr(n, d) for n, d in parts))
